import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const requests=[];
const handlers={};
const window={OuinpoTicketing:{root:'/tickets',nonce:'test'},addEventListener:(name,fn)=>{handlers[name]=fn;}};
let source=fs.readFileSync(new URL('../assets/js/front/ticket-simulator.js',import.meta.url),'utf8');
source=source.replace('  const stateNames =','  window.testDrafts = {DraftSync,drafts,draftSessions};\n  const stateNames =');
vm.runInNewContext(source,{window,document:{querySelectorAll:()=>[]},setTimeout,clearTimeout,fetch:(path,options)=>new Promise((resolve,reject)=>requests.push({path,body:JSON.parse(options.body),resolve: data=>resolve({ok:true,json:async()=>data}),reject}))});
const {DraftSync,drafts,draftSessions}=window.testDrafts;
const attempt={id:1,student_id:11,drafts:{revision:2,values:{'A:notes:message':'Restaurée'}}};
const sync=new DraftSync(attempt);
draftSessions.set(sync.prefix,sync);
assert.equal(drafts.get('11:1:A:notes:message'),'Restaurée');
assert.equal(sync.dirty(),false);
drafts.set('11:1:A:notes:message','Première saisie');
const saving=sync.flush();
assert.equal(requests.length,1);
assert.equal(requests[0].body.revision,2);
drafts.set('11:1:A:notes:message','Saisie plus récente');
requests.shift().resolve({revision:3});
await new Promise(resolve=>setImmediate(resolve));
assert.equal(requests[0].body.values['A:notes:message'],'Saisie plus récente');
assert.equal(requests[0].body.revision,3);
requests.shift().resolve({revision:4});
await saving;
assert.equal(sync.dirty(),false);
sync.adopt({revision:5,values:{}});
assert.equal(drafts.has('11:1:A:notes:message'),false,'Validated fields disappear');
drafts.set('11:1:A:notes:message','Non validée');
let prevented=false;
handlers.beforeunload({preventDefault(){prevented=true;}});
assert(prevented,'Unsaved work warns before leaving');
const failing=sync.flush();
const rejected=assert.rejects(failing,/Offline/);
requests.shift().reject(new Error('Offline'));
await rejected;
assert.equal(drafts.get('11:1:A:notes:message'),'Non validée');
assert(sync.failure && sync.dirty());
const retry=sync.flush();
requests.shift().resolve({revision:6});
await retry;
prevented=false; handlers.beforeunload({preventDefault(){prevented=true;}});
assert.equal(prevented,false,'Saved private drafts survive reload without a false warning');
drafts.set('11:1:A:notes:message','Edited during validation');
sync.adopt({revision:7,values:{}});
assert.equal(drafts.get('11:1:A:notes:message'),'Edited during validation','Late validation preserves newer edits');
sync.adopt({revision:1,values:{'A:notes:message':'stale'}});
assert.equal(sync.revision,7);
const other=new DraftSync({id:2,student_id:11,drafts:{revision:0,values:{}}});
assert.equal(Object.keys(other.values()).length,0,'Attempt isolation');
const desk=Object.create(window.OuinpoTicketUI.Desk.prototype);
let release;
desk.a={id:1};desk.ticketId='A';
desk.sync={paused:false,flush:()=>new Promise(resolve=>{release=resolve;}),adopt(){},dirty:()=>false};
let target;
desk.mutateSaved=async(path,method,body,ticket)=>{target=ticket;};
const action=desk.mutate('/notes','POST',{message:'Ticket A'});
desk.ticketId='B';release();await action;
assert.equal(target,'A','Navigation while awaiting autosave cannot redirect a mutation to another ticket');
console.log('Autosave: restoration, in-flight typing, dirty exit, retry, validation cleanup and isolation passed.');
